// Build PocketMesh into docs/ (served by GitHub Pages): one offline index.html + vendored three.js + PWA files.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
const root = path.dirname(new URL(import.meta.url).pathname);
const src = (f) => path.join(root, 'src', f);
const dist = path.join(root, 'docs');
const ORDER = ['mesh.js', 'modifiers.js', 'materials.js', 'uv.js', 'export.js', 'brres.js', 'brres_edit.js', 'measure.js', 'kcl.js', 'kmp.js', 'szs.js', 'app_core.js', 'app_transform.js', 'app_ops.js', 'app_uv.js', 'app_io.js', 'app_ruler.js', 'app_brres.js', 'app_track.js', 'app_szs.js', 'app_ui.js'];
const imports = new Set();
let code = '';
for (const f of ORDER) {
  if (!fs.existsSync(src(f))) { console.warn('WARNING: missing src/' + f); continue; }
  let s = fs.readFileSync(src(f), 'utf8');
  s = s.replace(/^import .*?;\s*$/gm, (m) => { imports.add(m.trim()); return ''; });
  s = s.replace(/^export\s+(?=(async\s+)?(function|const|let|class)\b)/gm, '');
  if (/^\s*import\s/m.test(s) || /^\s*export\s/m.test(s)) throw new Error('Unprocessed import/export in ' + f);
  code += `\n// ==== ${f} ====\n` + s;
}
const app = [...imports].join('\n') + '\n' + code;
const importmap = JSON.stringify({ imports: { three: './vendor/three.module.min.js', 'three/addons/': './vendor/addons/' } });
let html = fs.readFileSync(src('index.template.html'), 'utf8');
html = html.replace('/*IMPORTMAP*/', () => importmap).replace('/*APP*/', () => app);
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'vendor/addons/controls'), { recursive: true });
fs.mkdirSync(path.join(dist, 'vendor/addons/lines'), { recursive: true });
fs.mkdirSync(path.join(dist, 'vendor/addons/environments'), { recursive: true });
fs.mkdirSync(path.join(dist, 'icons'), { recursive: true });
fs.writeFileSync(path.join(dist, 'index.html'), html);
const three = path.join(root, 'node_modules/three');
const copies = [
  ['build/three.module.min.js', 'vendor/three.module.min.js'],
  ['examples/jsm/controls/TransformControls.js', 'vendor/addons/controls/TransformControls.js'],
  ['examples/jsm/lines/LineSegments2.js', 'vendor/addons/lines/LineSegments2.js'],
  ['examples/jsm/lines/LineSegmentsGeometry.js', 'vendor/addons/lines/LineSegmentsGeometry.js'],
  ['examples/jsm/lines/LineMaterial.js', 'vendor/addons/lines/LineMaterial.js'],
  ['examples/jsm/environments/RoomEnvironment.js', 'vendor/addons/environments/RoomEnvironment.js'],
];
for (const [a, b] of copies) fs.copyFileSync(path.join(three, a), path.join(dist, b));
fs.copyFileSync(path.join(three, 'LICENSE'), path.join(dist, 'vendor/THREE-LICENSE.txt'));
for (const f of fs.readdirSync(path.join(root, 'assets/icons'))) fs.copyFileSync(path.join(root, 'assets/icons', f), path.join(dist, 'icons', f));
const manifest = {
  name: 'PocketMesh', short_name: 'PocketMesh', description: 'Polygon modeling, UVs and textures on your phone.',
  start_url: './', scope: './', display: 'standalone', orientation: 'any',
  background_color: '#16181d', theme_color: '#16181d', categories: ['graphics', 'design', 'productivity'],
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
fs.writeFileSync(path.join(dist, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));
// service worker: precache everything, cache-first, versioned by content hash
const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else files.push(path.relative(dist, p)); } };
walk(dist);
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(dist, f)));
const version = hash.digest('hex').slice(0, 12);
const precache = ['./', ...files.filter((f) => f !== 'index.html')].map((f) => (f === './' ? f : './' + f));
fs.writeFileSync(path.join(dist, 'sw.js'), `// PocketMesh offline cache — generated by build.mjs
const CACHE = 'pocketmesh-${version}';
const FILES = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => caches.match('./'))));
});
`);
fs.writeFileSync(path.join(dist, '.nojekyll'), '');
console.log(`built docs/ (${files.length + 2} files, cache ${version}, index.html ${(html.length / 1024).toFixed(0)} KB)`);
